const COUNTRY_BY_CODE = new Map(
  COUNTRIES.map((country) => [country.code, country])
);

export function findCountry(input: string | null | undefined) {
  const key = (input ?? "").trim().toLowerCase().replace(/\s+/g, " ");
  if (!key) return null;
  const code = COUNTRY_ALIASES[key];
  return code ? COUNTRY_BY_CODE.get(code) ?? null : null;
}

export function currencyForCountry(input: string | null | undefined) {
  return findCountry(input)?.currency ?? null;
}

export function catalogCurrencyCodes() {
  return [...new Set(COUNTRIES.map((country) => country.currency))].sort();
}
